#!/usr/bin/env node
// Writes src/license-secret.js (gitignored) from CLUTTERDOCK_LICENSE_SECRET or
// ../scripts/private/license-secret.txt. Run automatically before packaging (predist).
// With --require, exits non-zero when no secret is available (used for release builds).
const fs = require('fs');
const path = require('path');

const requireSecret = process.argv.includes('--require');
const out = path.join(__dirname, '..', 'src', 'license-secret.js');

let secret = (process.env.CLUTTERDOCK_LICENSE_SECRET || '').trim();
if (!secret) {
  const privateFile = path.join(__dirname, '..', '..', 'scripts', 'private', 'license-secret.txt');
  if (fs.existsSync(privateFile)) {
    secret = fs.readFileSync(privateFile, 'utf8').split('\n')[0].trim();
  }
}

if (!secret) {
  if (requireSecret) {
    console.error(
      'ERROR: no license secret (set CLUTTERDOCK_LICENSE_SECRET or create scripts/private/license-secret.txt). ' +
        'Refusing to package a build that rejects real license keys.'
    );
    process.exit(1);
  }
  console.warn('write-license-secret: no secret found; skipping (dev fallback will be used).');
  process.exit(0);
}

fs.writeFileSync(out, `// Generated by scripts/write-license-secret.js — do not commit.\nmodule.exports = { SECRET: ${JSON.stringify(secret)} };\n`);
console.log('Wrote', out);
